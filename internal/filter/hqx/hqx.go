// Package hqx implements the hq2x, hq3x, and hq4x magnification filters.
//
// These games render 240x320. Shown at that size on a modern display they are
// a postage stamp, and scaled up by an integer factor they are a grid of large
// squares. hqx is the filter arcade emulators settled on for exactly this: it
// looks at each pixel's eight neighbours, decides which of them belong to the
// same shape, and draws the edges between shapes as diagonals rather than
// staircases. Flat areas stay flat, so the pixel art keeps its character.
//
// The 256-case decision table per filter — one case per combination of which
// neighbours differ — is the whole algorithm, and it is mechanically derived
// from Maxim Stepin's original. pattern2x.go, pattern3x.go, and pattern4x.go
// hold it, generated by translating the reference implementation case by case:
// all 256 patterns are covered exactly once in each, which is what makes the
// translation checkable rather than trusted.
//
