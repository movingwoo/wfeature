// Package glyph provides the runtime-authored 5x7 bitmap glyphs shared by
// text rendering paths. Unsupported Unicode characters map to a
// deterministic codepoint-marked box instead of disappearing from the frame.
package glyph

import "unicode"

// Pattern returns the seven row bitmasks (bit 4 is the left column) for a
// character. ASCII lowercase folds to the uppercase form.
func Pattern(character rune) [7]byte {
	if unicode.IsLower(character) && character <= unicode.MaxASCII {
		character = unicode.ToUpper(character)
	}
	if pattern, ok := patterns[character]; ok {
		return pattern
	}
	code := uint32(character)
	return [7]byte{0x1f, 0x11, byte(0x11 | (code>>1)&0x0e), byte(0x11 | (code>>5)&0x0e), byte(0x11 | (code>>9)&0x0e), 0x11, 0x1f}
}

// Columns reports the first and last used columns of a pattern, so
// proportional rendering can trim empty space.
func Columns(pattern [7]byte) (int, int) {
	first, last := 5, -1
	for _, row := range pattern {
		for column := 0; column < 5; column++ {
			if row&(1<<uint(4-column)) != 0 {
				if column < first {
					first = column
				}
				if column > last {
					last = column
				}
			}
		}
	}
	if last < first {
		return 0, 2
	}
	return first, last
}

