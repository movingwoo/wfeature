// applyDialFailureNotice makes a recognized client's failed dial reach the
// notice the title has for it. Every window is checked against the code that
// was examined before anything is written, and the archive is not touched.
// The handset plays no part: nothing on this path compares a subscriber.
func applyDialFailureNotice(memory *armcore.Memory, digest string) error {
	return applyCodeRewrites(memory, dialFailureRewrites[digest], "dial failure", digest)
}
